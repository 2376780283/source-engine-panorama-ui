	// panorama throws when a script registers for an event that no C++ code has declared; these
	// wrappers turn that into a no-op so a missing event cannot abort a whole script.
	// NOTE: do not try to declare the missing event from here - calling $.DefineEvent for a name that
	// panorama already knows *replaces* the C++ factory (and turns panel events into plain events),
	// which destabilises handlers.  Unknown names are declared on demand in C++ instead.
	function tolerant(name) {
		if (typeof $ === "undefined") { return; }
		var orig = $[name];
		if (typeof orig !== "function") { return; }
		$[name] = function () { try { return orig.apply($, arguments); } catch (e) { return 0; } };
	}
	tolerant("RegisterForUnhandledEvent");
	tolerant("UnregisterForUnhandledEvent");
	tolerant("RegisterEventHandler");
	tolerant("UnregisterEventHandler");

	// Install an override on a dotted API path ("MatchStatsAPI.GetUiExperienceType"), creating the
	// intermediate stubs on the way.  The value lands in the stub's override table (see makeStub).
	function seDefine(path, impl) {
		try {
			var parts = path.split(".");
			if (typeof g[parts[0]] === "undefined") { g[parts[0]] = makeStub(parts[0]); }
			var cur = g[parts[0]];
			for (var i = 1; i < parts.length - 1; i++) { cur = cur[parts[i]]; }
			cur[parts[parts.length - 1]] = impl;
		} catch (e) { }
	}

