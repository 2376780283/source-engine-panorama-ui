	//   overrides - entries installed by seDefine() below; they win over the placeholder behaviour,
	//               which is how a call can be made to answer with a real 0/false/"{}" instead of
	//               another truthy stub (see the "control flow" note further down).
	//   children  - memoised child stubs, so Api.Foo === Api.Foo (identity stability).
	function makeStub(name) {
		var overrides = Object.create(null);
		var children = Object.create(null);
		var fn = function () { return makeStub(name + "()"); };
		return new Proxy(fn, {
			get: function (target, prop) {
				if (typeof prop === "symbol") {
					// ToPrimitive: JS coerces the stub whenever it lands in a JSON.parse()/string/number
					// sink.  A stub is an object, so it is *always* truthy and it can never look like a
					// "no data" answer; at least make the coercions harmless - an empty document parses,
					// and arithmetic sees 0.
					if (prop === Symbol.toPrimitive) {
						return function (hint) { return hint === "number" ? 0 : "[]"; };
					}
					return undefined;
				}
				if (hasOwn(overrides, prop)) { return overrides[prop]; }
				// Behave like an empty collection: panorama converts .length results straight into numbers, and a
				// stub object there made V8ParamToPanoramaType throw (and the throw took the game down).
				if (prop === "length" || prop === "size" || prop === "count") { return 0; }
				// Explicit .toString()/.valueOf() calls (and anything that does not go through
				// ToPrimitive) also get the harmless empty-document / zero answer.
				if (prop === "toString") { return function () { return "[]"; }; }
				if (prop === "valueOf") { return function () { return 0; }; }
				if (prop === "then") { return undefined; } // do not look like a promise
				if (!hasOwn(children, prop)) { children[prop] = makeStub(name + "." + String(prop)); }
				return children[prop];
			},
			set: function (target, prop, value) {
				if (typeof prop === "string") { overrides[prop] = value; }
				return true;
			},
			apply: function () { return makeStub(name + "()"); },
			construct: function () { return makeStub(name + "()"); },
			has: function () { return true; }
		});
	}

